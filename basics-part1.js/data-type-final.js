// datatype are two types in javascript

// 1. primitive datatype
// 2. non-primitive datatype

// 1. primitive datatype
// Primitive data types are the most basic data types in JavaScript. They are immutable, meaning their values cannot be changed once they are created. 
// The primitive data types in JavaScript include:

// 1. Number: Represents numeric values, including integers and floating-point numbers.
//  Example: 42, 3.14

// 2. String: Represents a sequence of characters enclosed in single quotes, double quotes, or backticks. 
// Example: 'Hello', "World", `Template Literal`

// 3. Boolean: Represents a logical value that can be either true or false.
//  Example: true, false

// 4. Null: Represents the intentional absence of any object value. It is a primitive value that indicates "no value" or "empty". 
// Example: null

// 5. Undefined: Represents a variable that has been declared but has not been assigned a value.
//  Example: undefined

// 6. Symbol: Represents a unique and immutable value that can be used as an identifier for object properties.
//  Example: Symbol('description')

// 7. BigInt: Represents whole numbers larger than the maximum safe integer value for the Number type.
//  Example: 1234567890123456789012345678901234567890n






// 2. non-primitive datatype
// Non-primitive data types, also known as reference types, are more complex data structures that can hold multiple values and can be modified. 
// The non-primitive data types in JavaScript include:

// 1. Object: Represents a collection of key-value pairs, where each key is a string (or symbol) and each value can be of any data type.
// Example: { name: 'John', age: 30 }

// 2. Array: Represents an ordered list of values, which can be of any data type. Arrays are a special type of object in JavaScript.
// Example: [1, 2, 3, 'four', true]

// 3. Function: Represents a reusable block of code that can be called and executed. Functions are also objects in JavaScript.
// Example: function greet() { console.log('Hello!'); }

// reference types are mutable, meaning their values can be changed after they are created. When you assign a reference type to a variable, you are actually assigning a reference (or pointer) to the object in memory, rather than the object itself. This means that if you modify the object through one variable, the changes will be reflected in all other variables that reference the same object.
